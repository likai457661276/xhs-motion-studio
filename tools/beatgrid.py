#!/usr/bin/env python3
"""beatgrid.py — check that picture cues sit on the music grid (MIT License).

  python3 beatgrid.py <project> [--cut-subdiv 1] [--hit-subdiv 2] [--tol-ms 1] [--onset-tol-ms 20] [--no-audio]

Checks
  1. every cut (scene start) lies on the beat grid (1/cut-subdiv beat), every hit/heavy on 1/hit-subdiv beat
  2. every cue is frame-exact (t × fps is an integer) so picture and sound cannot drift by rounding
  3. storyboard.json and the generated music agree (BPM, cue list) — otherwise the BGM is stale
  4. (audio) an onset really happens at each cut/heavy: spectral-flux peak within ±onset-tol-ms
Writes build/beatgrid-report.json; exit 1 on failure.
"""
import argparse, json, sys, wave
from pathlib import Path
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))  # sibling module xms.py
import xms  # noqa: E402


def onsets(wav, cues, win_ms=40):
    with wave.open(str(wav)) as w:
        sr, ch = w.getframerate(), w.getnchannels()
        x = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).astype(np.float32).reshape(-1, ch).mean(1) / 32768
    hop, n = int(sr * .002), int(sr * .016)
    frames = np.lib.stride_tricks.sliding_window_view(np.pad(x, (n, n)), n)[::hop]
    spec = np.abs(np.fft.rfft(frames * np.hanning(n), axis=1))
    flux = np.r_[0, np.maximum(0, np.diff(np.log1p(spec * 20), axis=0)).sum(1)]
    res = []
    for c in cues:
        i = int(round((c['t'] * sr + n / 2) / hop))  # frame whose window is centred on the cue
        r = int(win_ms / 2)
        lo, hi = max(0, i - r), min(len(flux), i + r + 1)
        k = lo + int(np.argmax(flux[lo:hi]))
        base = np.median(flux[max(0, i - 250):i - r]) if i - r > 10 else np.median(flux)
        res.append({**c, 'onsetOffsetMs': round((k - i) * hop / sr * 1000, 1), 'strength': round(float(flux[k] / (base + 1e-6)), 1)})
    return res


def main():
    ap = argparse.ArgumentParser(prog='beatgrid', description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('project'); ap.add_argument('--cut-subdiv', type=int, default=1); ap.add_argument('--hit-subdiv', type=int, default=2)
    ap.add_argument('--tol-ms', type=float, default=1.0); ap.add_argument('--onset-tol-ms', type=float, default=20.0); ap.add_argument('--no-audio', action='store_true')
    a = ap.parse_args()
    root = Path(a.project).resolve(); film = xms.load_film(root); mu = film.get('music', {}); fps = film['fps']
    bpm = mu.get('bpm', 120); B = 60 / bpm
    cues, cur = [], 0
    for i, sc in enumerate(film['scenes']):
        start = cur / fps
        if i: cues.append({'t': round(start, 6), 'kind': 'cut', 'scene': sc['id']})
        for h in sc.get('hits', []):
            cues.append({'t': round(start + h, 6), 'kind': 'heavy' if h in sc.get('heavy', []) else 'hit', 'scene': sc['id']})
        cur += round(sc['seconds'] * fps)
    cues.sort(key=lambda c: (c['t'], c['kind']))
    problems, rows = [], []
    for c in cues:
        sub = a.cut_subdiv if c['kind'] == 'cut' else a.hit_subdiv
        g = B / sub; err = (c['t'] / g - round(c['t'] / g)) * g * 1000
        fr = c['t'] * fps; ferr = abs(fr - round(fr))
        row = {**c, 'beat': round(c['t'] / B, 3), 'gridErrorMs': round(err, 3), 'frame': round(fr, 3)}
        rows.append(row)
        if abs(err) > a.tol_ms: problems.append(f'{c["kind"]} {c["scene"]} @ {c["t"]}s is {err:+.1f} ms off the 1/{sub}-beat grid')
        if ferr > 1e-6: problems.append(f'{c["kind"]} {c["scene"]} @ {c["t"]}s is not frame-exact ({fr:.3f})')
    music_file = root / mu.get('file', 'audio/bgm.wav'); meta_file = music_file.with_suffix('.json')
    audio = None
    if meta_file.exists():
        meta = xms.read(meta_file)
        if abs(meta['bpm'] - bpm) > 1e-9: problems.append(f'music generated at {meta["bpm"]} BPM but storyboard.json says {bpm}')
        gen = sorted(((round(c['t'], 3), c['kind']) for c in meta['cues']))
        want = sorted(((round(c['t'], 3), c['kind']) for c in cues))
        if gen != want: problems.append('BGM is stale: its cue list differs from storyboard.json — rerun `xms.py bgm`')
        if abs(meta['durationSeconds'] - cur / fps) > 1e-3: problems.append(f'BGM length {meta["durationSeconds"]}s != film {cur / fps}s')
    else:
        problems.append(f'{meta_file.relative_to(root)} missing (music not generated by bgm.py; grid checked against storyboard.json BPM only)')
    if not a.no_audio and music_file.exists():
        audio = onsets(music_file, [c for c in cues if c['kind'] in ('cut', 'heavy')])
        for o in audio:
            if abs(o['onsetOffsetMs']) > a.onset_tol_ms or o['strength'] < 1.5:
                problems.append(f'no clear audio onset at {o["kind"]} {o["scene"]} {o["t"]}s (offset {o["onsetOffsetMs"]} ms, strength {o["strength"]})')
    rep = {'passed': not problems, 'bpm': bpm, 'beatSeconds': B, 'fps': fps, 'cutSubdiv': a.cut_subdiv, 'hitSubdiv': a.hit_subdiv,
           'counts': {k: sum(c['kind'] == k for c in cues) for k in ('cut', 'hit', 'heavy')}, 'maxGridErrorMs': max((abs(r['gridErrorMs']) for r in rows), default=0),
           'audioOnsets': audio and {'checked': len(audio), 'maxAbsOffsetMs': max(abs(o['onsetOffsetMs']) for o in audio), 'minStrength': min(o['strength'] for o in audio)},
           'problems': problems, 'cues': rows, 'onsetDetail': audio}
    xms.write(root / 'build/beatgrid-report.json', rep)
    c = rep['counts']
    print(f'beat grid {bpm:g} BPM: {c["cut"]} cuts, {c["hit"]} hits, {c["heavy"]} heavy · max grid error {rep["maxGridErrorMs"]} ms'
          + (f' · audio onsets {rep["audioOnsets"]["checked"]} checked, max offset {rep["audioOnsets"]["maxAbsOffsetMs"]} ms' if audio else ''))
    for p in problems: print('  - ' + p)
    print('PASS' if not problems else 'FAIL')
    sys.exit(0 if not problems else 1)


if __name__ == '__main__':
    main()
